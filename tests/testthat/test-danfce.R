test_that("o DANFE NFC-e na bobina: os itens, o pagamento, a chave, o consumidor e o protocolo", {
  skip_if_not_installed("pdftools")
  skip_if_not_installed("qrcode")
  arquivo = tempfile(fileext = ".pdf")
  expect_identical(danfce_pdf(system.file("exemplos", "nfce_ce_contingencia.xml", package = "RNFe"), arquivo), arquivo)
  expect_identical(pdftools::pdf_info(arquivo)$pages, 1L)
  # A largura da bobina de 80 mm (em pontos: 8 / 2,54 * 72).
  expect_equal(pdftools::pdf_pagesize(arquivo)$width, 8 / 2.54 * 72, tolerance = 1)
  texto = gsub("\\s+", " ", gsub("\u00ad", "-", pdftools::pdf_text(arquivo), fixed = TRUE))
  expect_match(texto, "Documento Auxiliar da Nota Fiscal de Consumidor Eletr\u00f4nica", fixed = TRUE)
  expect_match(texto, "Valor total R$ 35,00", fixed = TRUE)
  expect_match(texto, "Troco R$ 15,00", fixed = TRUE)
  expect_match(texto, "2326 1011 4447 7700 0161 6500 3000 0000 7791 3572 4686", fixed = TRUE)
  expect_match(texto, "CONSUMIDOR N\u00c3O IDENTIFICADO", fixed = TRUE)
  expect_match(texto, "323260000004321", fixed = TRUE)
  expect_match(texto, "SEM VALOR FISCAL", fixed = TRUE)
})

test_that("o DANFE NFC-e em conting\u00eancia, e as notas que n\u00e3o servem", {
  skip_if_not_installed("pdftools")
  skip_if_not_installed("qrcode")
  nota = paste(readLines(system.file("exemplos", "nfce_ce_contingencia.xml", package = "RNFe"), encoding = "UTF-8"), collapse = "\n")
  sem_protocolo = sub("(?s)<protNFe.*</protNFe>", "", nota, perl = TRUE)
  arquivo = tempfile(fileext = ".pdf")
  danfce_pdf(sem_protocolo, arquivo)
  texto = gsub("\\s+", " ", pdftools::pdf_text(arquivo))
  expect_match(texto, "EMITIDA EM CONTING\u00caNCIA", fixed = TRUE)
  expect_match(texto, "Pendente de autoriza\u00e7\u00e3o", fixed = TRUE)
  sem_qrcode = sub("(?s)<infNFeSupl>.*</infNFeSupl>", "", nota, perl = TRUE)
  expect_error(danfce_pdf(sem_qrcode, tempfile(fileext = ".pdf")), "nfce_qrcode")
  expect_error(danfce_pdf(system.file("exemplos", "nfe_proc_sp.xml", package = "RNFe"), tempfile(fileext = ".pdf")), "danfe_pdf")
})
