test_that("o DAMDFE do rodovi\u00e1rio: a identifica\u00e7\u00e3o, as quantidades, o protocolo, o ve\u00edculo e o condutor", {
  skip_if_not_installed("pdftools")
  skip_if_not_installed("qrcode")
  arquivo = tempfile(fileext = ".pdf")
  expect_identical(damdfe_pdf(system.file("exemplos", "mdfe_proc_sp.xml", package = "RNFe"), arquivo), arquivo)
  expect_identical(pdftools::pdf_info(arquivo)$pages, 1L)
  texto = gsub("\\s+", " ", gsub("\u00ad", "-", pdftools::pdf_text(arquivo), fixed = TRUE))
  expect_match(texto, "Documento Auxiliar de Manifesto Eletr\u00f4nico de Documentos Fiscais", fixed = TRUE)
  expect_match(texto, "3526 1033 3444 5550 0070 5800 1000 0003 2111 1223 3448", fixed = TRUE)
  expect_match(texto, "935260000011111", fixed = TRUE)
  expect_match(texto, "120,50", fixed = TRUE)
  expect_match(texto, "ABC1D23", fixed = TRUE)
  expect_match(texto, "MOTORISTA DE TESTE", fixed = TRUE)
  expect_match(texto, "SEM VALOR FISCAL", fixed = TRUE)
  expect_error(damdfe_pdf(system.file("exemplos", "nfe_proc_sp.xml", package = "RNFe"), tempfile(fileext = ".pdf")), "MDF-e")
})
