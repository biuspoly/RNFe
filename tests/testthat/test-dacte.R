test_that("o DACTE do CT-e e o do CT-e OS: a identifica\u00e7\u00e3o, a chave, o protocolo e as pessoas", {
  skip_if_not_installed("pdftools")
  skip_if_not_installed("qrcode")
  arquivo = tempfile(fileext = ".pdf")
  expect_identical(dacte_pdf(system.file("exemplos", "cte_proc_sp.xml", package = "RNFe"), arquivo), arquivo)
  expect_identical(pdftools::pdf_info(arquivo)$pages, 1L)
  texto = gsub("\\s+", " ", gsub("\u00ad", "-", pdftools::pdf_text(arquivo), fixed = TRUE))
  expect_match(texto, "Documento Auxiliar do Conhecimento de Transporte", fixed = TRUE)
  expect_match(texto, "3526 1012 ABC3 4501 DE35 5700 1000 0005 5518 7654 3210", fixed = TRUE)
  expect_match(texto, "135260000098765", fixed = TRUE)
  expect_match(texto, "TOMADOR DO SERVI\u00c7O", fixed = TRUE)
  expect_match(texto, "TRANSPORTADORA DE TESTE LTDA", fixed = TRUE)
  arquivo_os = tempfile(fileext = ".pdf")
  dacte_pdf(system.file("exemplos", "cte_os_sp.xml", package = "RNFe"), arquivo_os)
  texto_os = gsub("\\s+", " ", gsub("\u00ad", "-", pdftools::pdf_text(arquivo_os), fixed = TRUE))
  expect_match(texto_os, "DACTE OS", fixed = TRUE)
  expect_match(texto_os, "FRETAMENTO 1.000,00", fixed = TRUE)
  expect_match(texto_os, "135260000054321", fixed = TRUE)
  expect_error(dacte_pdf(system.file("exemplos", "nfe_proc_sp.xml", package = "RNFe"), tempfile(fileext = ".pdf")), "CT-e")
})
